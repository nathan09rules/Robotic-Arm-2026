async def send_pose(bone_name, x, y, z):
    reader, writer = await asyncio.open_connection('127.0.0.1', 9999)
    writer.write(f"{bone_name}:{x},{y},{z}".encode())
    await writer.drain()
    writer.close()
    await writer.wait_closed()

async def get_bone_rotation(bone_name):
    reader, writer = await asyncio.open_connection('127.0.0.1', 9999)
    writer.write(f"GET:{bone_name}".encode())
    await writer.drain()
    response = (await reader.read(1024)).decode()
    writer.close()
    await writer.wait_closed()
    return tuple(float(v) for v in response.split(","))

